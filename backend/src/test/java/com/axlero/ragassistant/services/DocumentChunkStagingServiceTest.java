package com.axlero.ragassistant.services;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import com.axlero.ragassistant.entities.DocumentIngestionChunk;
import com.axlero.ragassistant.entities.DocumentRecord;
import com.axlero.ragassistant.entities.DocumentStatus;
import com.axlero.ragassistant.repositories.DocumentIngestionChunkRepository;
import com.axlero.ragassistant.repositories.DocumentRecordRepository;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.test.util.ReflectionTestUtils;

class DocumentChunkStagingServiceTest {

    private DocumentIngestionChunkRepository chunkRepository;
    private DocumentRecordRepository documentRepository;
    private DocumentChunkStagingService stagingService;

    @BeforeEach
    void setUp() {
        chunkRepository = mock(DocumentIngestionChunkRepository.class);
        documentRepository = mock(DocumentRecordRepository.class);

        stagingService = new DocumentChunkStagingService(
                chunkRepository, documentRepository);
    }

    @Test
    @SuppressWarnings("unchecked")
    void stagesDocumentAsProcessingAndSavesEveryChunk() {
        UUID ownerId = UUID.randomUUID();
        UUID documentId = UUID.randomUUID();

        // Simulate the ID generated by the database.
        when(documentRepository.saveAndFlush(any(DocumentRecord.class)))
                .thenAnswer(invocation -> {
                    DocumentRecord record = invocation.getArgument(0);
                    ReflectionTestUtils.setField(record, "id", documentId);
                    return record;
                });

        DocumentRecord result = stagingService.stageDocument(
                "guide.txt",
                "text/plain",
                11L,
                ownerId,
                List.of("first chunk", "second chunk"));

        assertEquals(documentId, result.getId());
        assertEquals(DocumentStatus.PROCESSING, result.getStatus());

        ArgumentCaptor<List<DocumentIngestionChunk>> captor =
                ArgumentCaptor.forClass(List.class);
        verify(chunkRepository).saveAll(captor.capture());
        verify(chunkRepository).flush();

        List<DocumentIngestionChunk> saved = captor.getValue();
        assertEquals(2, saved.size());
        assertEquals("first chunk", saved.get(0).getContent());
        assertEquals("second chunk", saved.get(1).getContent());
    }

    @Test
    void returnsStagedChunksForDocument() {
        UUID documentId = UUID.randomUUID();
        List<DocumentIngestionChunk> chunks = List.of(
                new DocumentIngestionChunk(documentId, 0, "first chunk"),
                new DocumentIngestionChunk(documentId, 1, "second chunk"));

        when(chunkRepository.findAllByDocumentIdOrderByChunkIndex(documentId))
                .thenReturn(chunks);

        List<DocumentIngestionChunk> result =
                stagingService.getStagedChunks(documentId);

        assertSame(chunks, result);
    }

    @Test
    void clearsStagedChunksForDocument() {
        UUID documentId = UUID.randomUUID();

        stagingService.clearStagedChunks(documentId);

        verify(chunkRepository).deleteAllByDocumentId(documentId);
    }
}
